// ============================================================================
//  حسابدار — build.rs
//  ---------------------------------------------------------------------------
//  آماده‌سازیِ فایل‌های وب (پوشهٔ dist-web) اینجا انجام نمی‌شود، چون CLIِ Tauri وجودِ
//  frontendDist را **پیش از** اجرای cargo بررسی می‌کند و build.rs بعد از آن اجرا می‌شود.
//  آن کار در prepare-dist.ps1 انجام می‌شود که Tauri خودش به‌عنوان beforeBuildCommand
//  اجرایش می‌کند (تنظیم‌شده در tauri.conf.json).
//
//  تنها کارِ اینجا: وقتی فایل‌های وب عوض شدند، cargo بداند که باید دوباره بیلد کند —
//  وگرنه generate_context!() دارایی‌های قدیمی را در باینری نگه می‌دارد.
// ============================================================================

fn main() {
    // اگر فایل‌های وب (یا اسکریپتِ آماده‌سازی) تغییر کردند، بیلد دوباره انجام شود.
    println!("cargo:rerun-if-changed=dist-web");
    println!("cargo:rerun-if-changed=../prepare-dist.ps1");
    println!("cargo:rerun-if-changed=src/share_win.ps1");

    tauri_build::build()
}
